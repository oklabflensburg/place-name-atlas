test('initial maps load while region choices are still pending',async({page})=>{
  let release:()=>void=()=>{}
  const held=new Promise<void>(resolve=>release=resolve)
  let scope:string|null=null
  await page.route('**/api/v1/regions?*',async route=>{
    scope=new URL(route.request().url()).searchParams.get('scope')
    await held;await route.continue().catch(()=>{})
  })
  try{
    await page.goto('/');await ready(page)
    expect(scope).toBe('overview')
    await expect(page.locator('.ending-card[aria-busy=false]')).toHaveCount(10)
  }finally{release()}
  await expect(page.getByLabel('Region',{exact:true}).first().locator('option[value="state:01"]')).toHaveCount(1)
})
