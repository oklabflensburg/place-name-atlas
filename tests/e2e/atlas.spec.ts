test('loading, zero hits, no data, API failure and retry are distinct',async({page})=>{
  let release:()=>void=()=>{}
  const held=new Promise<void>(r=>release=r)
  await page.route('**/api/v1/grid/counts?*',async r=>{await held;await r.continue()})
  await page.goto('/');await expect(page.locator('.ending-card')).toHaveCount(10)
  await expect(page.locator('.ending-card[aria-busy=true]')).toHaveCount(10)
  release();await ready(page);await page.unroute('**/api/v1/grid/counts?*')
  await change(page,'ach','neverexists')
  await expect(page.locator('.ending-card').first()).toContainText('Keine passenden Orte')
  await expect(page.locator('.ending-card').first().locator('svg')).toBeVisible()
  await page.route('**/api/v1/grid/counts?*',r=>r.fulfill({status:503,contentType:'application/json',body:JSON.stringify({message:'Testausfall der Raster-API'})}))
  await selectOverviewFilter(page,'Ortsart','district')
  await expect(page.locator('.card-error').first()).toContainText('Testausfall')
  await expect(page.locator('.ending-card').first()).toContainText('Daten nicht geladen')
  await expect(page.locator('.ending-card').first()).not.toContainText('Keine passenden Orte')
  await page.unroute('**/api/v1/grid/counts?*')
  for(const card of await page.locator('.ending-card').all())await card.getByRole('button',{name:'Erneut versuchen',exact:true}).click()
  await ready(page)
  await page.getByRole('button',{name:'Zellwerte für -neverexists öffnen'}).click()
  const select=page.getByLabel('Zelle auswählen')
  const noData=await page.locator('.ending-card').first().locator('[data-denominator="0"]').first().getAttribute('data-cell')
  expect(noData).toBeTruthy();await select.selectOption(noData!)
  await expect(page.getByRole('dialog')).toContainText('Keine Daten: Hier sind keine Orte erfasst.')
})
test('a superseded response cannot overwrite a newer shared filter',async({page})=>{
  await page.goto('/');await ready(page)
  let release:()=>void=()=>{}
  const held=new Promise<void>(r=>release=r)
  await page.route('**/api/v1/grid/counts?*',async r=>{
    const f=JSON.parse(new URL(r.request().url()).searchParams.get('q')!)
    if(f.kinds[0]==='settlement')await held
    await r.continue().catch(()=>{})
  })
  await selectOverviewFilter(page,'Ortsart','settlement')
  await selectOverviewFilter(page,'Ortsart','district');await ready(page)
  release()
  await expect.poll(()=>JSON.parse(new URL(page.url()).searchParams.get('s')||'{}').kind).toBe('district')
  await expect(page.locator('.overview-coverage strong')).toHaveText('7')
})
